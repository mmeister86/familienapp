// Vendored synchronous SHA-256 (FIPS 180-4, public-domain algorithm).
//
// calendarSync mutations must compute the import content fingerprint inside
// the Convex runtime, where `node:crypto` imports are unavailable and async
// WebCrypto cannot be relied on under convex-test. This dependency-free
// implementation runs identically in Convex mutations, Node actions and the
// edge-runtime test project. UTF-8 encoding is done by hand so the helper
// never depends on TextEncoder availability.

